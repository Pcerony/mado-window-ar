async (page) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('http://localhost:4178/');
  if(!await page.locator('#camera').count())throw Error('Home is not the phone app');
  await page.getByRole('button',{name:'このまま AR を始める',exact:true}).waitFor();
  await page.evaluate(()=>{window.cameraCalls=0;navigator.mediaDevices.getUserMedia=async()=>{window.cameraCalls++;throw Object.assign(new Error(),{name:'NotAllowedError'})}});
  await page.getByRole('button',{name:'このまま AR を始める',exact:true}).click();
  await page.getByRole('button',{name:'もう一度試す',exact:true}).waitFor();
  if(await page.locator('#rotate-device').isVisible())throw Error('Portrait gate stayed blocking');
  if(await page.evaluate(()=>window.cameraCalls)!==1)throw Error('Camera was not requested exactly once');
  if(!(await page.locator('#camera-message').textContent()).includes('Chrome'))throw Error('Wrong permission instructions for Chrome');
  await page.goto('http://localhost:4178/ar.html?w=987&h=456');
  await page.waitForURL('**/?w=987&h=456');
  await page.setViewportSize({width:1920,height:1080});
  await page.goto('http://localhost:4178/screen.html?scene=coast');
  if(await page.locator('.ar-marker:visible').count()!==4)throw Error('Screen does not show tracking markers by default');
  await page.locator('#room-join img').waitFor();
  await page.locator('#room-join img').evaluate(img=>img.decode());
  await page.addScriptTag({path:'/Users/heisei/Library/CloudStorage/OneDrive-个人/Desktop/vivitstop/train-window/node_modules/jsqr/dist/jsQR.js'});
  const box=await page.locator('#room-join a').boundingBox();
  if(box.width<350)throw Error('Room QR too small on a 1080p display');
  const qr=(await page.screenshot({clip:box})).toString('base64');
  const decoded=await page.evaluate(async(data)=>{const img=new Image();img.src='data:image/png;base64,'+data;await img.decode();const c=document.createElement('canvas');c.width=c.height=180;const ctx=c.getContext('2d');ctx.drawImage(img,0,0,180,180);const p=ctx.getImageData(0,0,180,180);return jsQR(p.data,180,180)?.data},qr);
  if(decoded!=='armado.heisei.space')throw Error('Supplied QR did not decode after downscaling: '+decoded);
  const overlap=await page.evaluate(()=>{const q=document.querySelector('#room-join').getBoundingClientRect();return [...document.querySelectorAll('.ar-marker')].some(el=>{const m=el.getBoundingClientRect();return q.left<m.right&&q.right>m.left&&q.top<m.bottom&&q.bottom>m.top})});
  if(overlap)throw Error('Room QR overlaps screen tracking markers');
  await page.screenshot({path:'output/playwright/room-qr-1920.png'});
  await page.setViewportSize({width:3840,height:2160});
  const large=await page.locator('#room-join a').boundingBox();
  if(large.width<500||large.x+large.width>3840)throw Error('4K QR did not scale up');
  return {rootPhone:true,portraitOptional:true,ChromePermissionPromptPath:true,legacyLinkPreserved:true,roomQR:decoded,width1080p:box.width,width4k:large.width,markerOverlap:false};
}
