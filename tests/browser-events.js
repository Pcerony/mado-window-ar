async (page) => {
  await page.setViewportSize({width:1280,height:800});
  await page.goto('http://localhost:4178/screen.html?ar');
  await page.getByRole('button',{name:'暂停',exact:true}).click();
  const inland=(await page.screenshot()).toString('base64');
  await page.locator('#scene').selectOption('coast');
  const coast=(await page.screenshot()).toString('base64');
  await page.setViewportSize({width:844,height:390});
  await page.addInitScript(()=>{Math.random=()=>.5});
  await page.goto('http://localhost:4178/');
  await page.evaluate(async({inland,coast})=>{
    const load=async(data)=>{const img=new Image();img.src='data:image/png;base64,'+data;await img.decode();return img};
    const images={inland:await load(inland),coast:await load(coast)};
    const input=document.createElement('canvas');input.width=1280;input.height=720;
    const ctx=input.getContext('2d');window.qaRoute='coast';
    const draw=()=>{ctx.fillStyle='#263329';ctx.fillRect(0,0,1280,720);ctx.drawImage(images[window.qaRoute],128,40,1024,640)};
    draw();window.qaTimer=setInterval(draw,50);navigator.mediaDevices.getUserMedia=async()=>input.captureStream(20);
  },{inland,coast});
  await page.getByRole('button',{name:'カメラを起動',exact:true}).click();
  await page.waitForFunction(()=>document.body.classList.contains('locked'));
  await page.waitForFunction(()=>document.querySelector('#creature').dataset.encounter==='approach',null,{timeout:40000});
  await page.screenshot({path:'output/playwright/event-ferry-approach.png'});
  await page.waitForFunction(()=>document.querySelector('#creature').dataset.encounter==='lift');
  await page.screenshot({path:'output/playwright/event-ferry-lift.png'});
  await page.getByRole('dialog').waitFor({state:'visible'});
  await page.getByRole('heading',{name:'さんふらわあ',exact:true}).waitFor();
  await page.getByText('掲載航路では、福岡県内への寄港はありません。',{exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/event-ferry-info.png'});
  if(await page.locator('#creature').getAttribute('data-facing')!=='1.00')throw Error('Monster is not facing the viewer');
  await page.getByRole('button',{name:'会話を閉じる',exact:true}).click();
  await page.waitForFunction(()=>{let d=document.querySelector('#creature').dataset;return d.subject==='kamome'&&d.encounter==='approach'&&+d.eventTime>=1.8},null,{timeout:40000});
  await page.screenshot({path:'output/playwright/event-kamome-near.png'});
  await page.waitForFunction(()=>{let d=document.querySelector('#creature').dataset;return d.encounter==='approach'&&+d.eventTime>=3.45});
  await page.screenshot({path:'output/playwright/event-kamome-far.png'});
  await page.getByRole('heading',{name:'かもめ',exact:true}).waitFor({state:'visible'});
  await page.screenshot({path:'output/playwright/event-kamome-info.png'});
  await page.getByRole('button',{name:'会話を閉じる',exact:true}).click();
  await page.evaluate(()=>{window.qaRoute='inland'});
  await page.waitForFunction(()=>{let d=document.querySelector('#creature').dataset;return d.subject==='museum'&&d.encounter==='approach'},null,{timeout:40000});
  await page.screenshot({path:'output/playwright/event-museum-approach.png'});
  await page.getByRole('heading',{name:'九州国立博物館',exact:true}).waitFor({state:'visible'});
  await page.screenshot({path:'output/playwright/event-museum-info.png'});
  await page.setViewportSize({width:667,height:375});
  await page.screenshot({path:'output/playwright/event-museum-small-phone.png'});
  const result=await page.evaluate(()=>{const box=document.querySelector('#encounter-dialog').getBoundingClientRect(),c=document.querySelector('#creature'),data=c.getContext('2d').getImageData(0,0,1400,750).data;let pixels=0;for(let i=3;i<data.length;i+=4)if(data[i])pixels++;return {creaturePixels:pixels,overflow:document.documentElement.scrollWidth>innerWidth,dialogFits:box.left>=0&&box.right<=innerWidth&&box.top>=0&&box.bottom<=innerHeight}});
  if(result.overflow||!result.dialogFits||result.creaturePixels<1000)throw Error(JSON.stringify(result));
  await page.getByRole('button',{name:'カメラを停止',exact:true}).click();
  if(await page.getByRole('dialog').isVisible())throw Error('Stopping camera left dialogue visible');
  return {...result,ferry:true,kamomeNearThenFar:true,museum:true,JapaneseDialogue:true};
}
